export function findByName(list,name) {
  return list.find(x=>x.name===name) || null;
}

export function closestFallback(list,name,defaultValue) {
  const exact=findByName(list,name);
  if (exact) return exact.fallbackUsed;
  const q=String(name||"").toLowerCase();
  const partial=list.find(x=>q.includes(x.name.toLowerCase()) || x.name.toLowerCase().includes(q));
  return partial?.fallbackUsed ?? defaultValue;
}


function normalizePartText(value){
  return String(value||"")
    .toLowerCase()
    .replace(/geforce|nvidia|amd\s+radeon|radeon/g," ")
    .replace(/intel\s+core/g,"intel")
    .replace(/[^a-z0-9]+/g,"")
    .trim();
}

function modelDigits(value){
  const raw=String(value||"").toLowerCase().replace(/(?<=\d)o\b/g,"0");
  const nums=raw.match(/\d{3,5}/g)||[];
  return nums;
}

function levenshtein(a,b){
  if(a===b) return 0;
  if(!a.length) return b.length;
  if(!b.length) return a.length;
  const row=Array.from({length:b.length+1},(_,i)=>i);
  for(let i=1;i<=a.length;i++){
    let prev=row[0];
    row[0]=i;
    for(let j=1;j<=b.length;j++){
      const temp=row[j];
      row[j]=Math.min(row[j]+1,row[j-1]+1,prev+(a[i-1]===b[j-1]?0:1));
      prev=temp;
    }
  }
  return row[b.length];
}

function aliasKeys(item,type){
  const keys=new Set([normalizePartText(item.name)]);
  let n=item.name.toLowerCase();
  if(type==="gpu"){
    n=n.replace(/^intel\s+/,"").replace(/^nvidia\s+/,"").replace(/^amd\s+/,"");
    keys.add(normalizePartText(n));
    keys.add(normalizePartText(n.replace(/\s+(2gb|3gb|4gb|6gb|8gb|10gb|11gb|12gb|16gb|20gb|24gb|32gb)$/i,"")));
  }
  if(type==="cpu"){
    keys.add(normalizePartText(n.replace(/^intel\s+/,"")));
    keys.add(normalizePartText(n.replace(/processor/g,"")));
  }
  return [...keys].filter(Boolean);
}

export function resolveCatalogPart(type,input){
  const list=type==="gpu"?GPUS:type==="cpu"?CPUS:[];
  const raw=String(input||"").trim();
  if(!raw) return {status:"unknown",input:raw,message:"No part entered."};

  const normalized=normalizePartText(raw.replace(/(?<=\d)[oO]\b/g,"0"));
  const directMatches=[];
  for(const item of list){
    const aliases=aliasKeys(item,type);
    if(aliases.includes(normalized)) directMatches.push(item);
  }
  const uniqueDirect=[...new Map(directMatches.map(x=>[x.name,x])).values()];
  if(uniqueDirect.length===1){
    const item=uniqueDirect[0];
    return {status:"exact",input:raw,canonical:item.name,item,confidence:1};
  }
  if(uniqueDirect.length>1){
    return {
      status:"ambiguous",
      input:raw,
      canonical:null,
      item:null,
      confidence:0,
      suggestions:uniqueDirect.map(x=>x.name),
      message:"Multiple real "+type.toUpperCase()+" variants match this input. Specify the exact variant."
    };
  }

  const inputNums=modelDigits(raw);
  const candidates=list.filter(item=>{
    const nums=modelDigits(item.name);
    return inputNums.length>0 && nums.some(n=>inputNums.includes(n));
  });

  const signature=value=>{
    const n=normalizePartText(value);
    const model=n.match(/(?:\d{3,5})(x3d|xtx|super|ti|xt|gre|kf|ks|k|f|g|x|t|s|m)?/);
    return [model?.[1]||"",n.match(/(\d+)gb/)?.[1]||""];
  };
  let best=null;
  for(const item of candidates){
    const requested=signature(raw),candidate=signature(item.name);
    if(requested[0]!==candidate[0] || (requested[1]&&requested[1]!==candidate[1]))continue;
    for(const key of aliasKeys(item,type)){
      const d=levenshtein(normalized,key);
      const maxLen=Math.max(normalized.length,key.length,1);
      const similarity=1-d/maxLen;
      if(!best||similarity>best.similarity) best={item,similarity};
    }
  }

  if(best&&best.similarity>=0.72){
    return {
      status:"fuzzy",
      input:raw,
      canonical:best.item.name,
      item:best.item,
      confidence:Number(best.similarity.toFixed(2)),
      message:"Interpreted as "+best.item.name
    };
  }

  const suggestions=list
    .map(item=>{
      const key=aliasKeys(item,type)[0];
      return {name:item.name,d:levenshtein(normalized,key)};
    })
    .sort((a,b)=>a.d-b.d)
    .slice(0,3)
    .map(x=>x.name);

  return {
    status:"unknown",
    input:raw,
    canonical:null,
    item:null,
    confidence:0,
    suggestions,
    message:"FlipScout does not recognize this as a known "+type.toUpperCase()+" model."
  };
}

export function resolveBuildParts(input){
  return {
    cpu:resolveCatalogPart("cpu",input.cpu),
    gpu:resolveCatalogPart("gpu",input.gpu)
  };
}

export function catalogGroup(type,name){
  const n=String(name||"");
  if(type==="gpu"){
    if(/^RTX 50/.test(n)) return "NVIDIA RTX 50 Series";
    if(/^RTX 40/.test(n)) return "NVIDIA RTX 40 Series";
    if(/^RTX 30/.test(n)) return "NVIDIA RTX 30 Series";
    if(/^RTX 20/.test(n)) return "NVIDIA RTX 20 Series";
    if(/^GTX 16|^GTX 10|^GTX 9|^GT /.test(n)) return "NVIDIA GTX / GT";
    if(/^RX 9/.test(n)) return "AMD Radeon RX 9000";
    if(/^RX 7/.test(n)) return "AMD Radeon RX 7000";
    if(/^RX 6/.test(n)) return "AMD Radeon RX 6000";
    if(/^RX 5\d{3}|^Radeon VII|^RX Vega/.test(n)) return "AMD Radeon RX 5000 / Vega";
    if(/^RX [45]\d{2}/.test(n)) return "AMD Radeon RX 400 / 500";
    if(/^Intel Arc B/.test(n)) return "Intel Arc B Series";
    if(/^Intel Arc A/.test(n)) return "Intel Arc A Series";
    return "Other GPU";
  }
  if(/^Ryzen/.test(n)){
    const model=(n.match(/\b(\d{4,5})/)||[])[1]||"";
    if(model.startsWith("9")) return "AMD Ryzen 9000";
    if(model.startsWith("8")) return "AMD Ryzen 8000";
    if(model.startsWith("7")) return "AMD Ryzen 7000";
    if(model.startsWith("5")) return "AMD Ryzen 5000";
    if(model.startsWith("4")) return "AMD Ryzen 4000";
    if(model.startsWith("3")) return "AMD Ryzen 3000";
    if(model.startsWith("2")) return "AMD Ryzen 2000";
    if(model.startsWith("1")) return "AMD Ryzen 1000";
  }
  if(/^Core Ultra/.test(n)) return "Intel Core Ultra Desktop";
  const intel=(n.match(/Intel i[3579]-(\d{4,5})/)||[])[1]||"";
  if(intel){
    const gen=intel.length===5?Number(intel.slice(0,2)):Number(intel[0]);
    return "Intel Core "+gen+"th Gen";
  }
  return "Other CPU";
}

export function groupedCatalog(type){
  const list=type==="gpu"?GPUS:CPUS;
  const groups={};
  for(const item of [...list].sort((a,b)=>a.name.localeCompare(b.name,undefined,{numeric:true}))){
    const group=catalogGroup(type,item.name);
    (groups[group]||(groups[group]=[])).push(item);
  }
  return groups;
}
